CREATE OR REPLACE FUNCTION private.reset_catalog()
 RETURNS TABLE(schema_name text, table_name text, classification text, strategy text, module text, backup boolean)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
 SELECT 'public',p.table_name,CASE WHEN p.table_name IN('donations','donation_webhook_events','support_tickets','support_ticket_messages','security_audit_log') THEN 'D' WHEN p.table_name='users' THEN 'C' WHEN p.reset_mode='clear' THEN 'A' ELSE 'B' END,
 CASE WHEN p.table_name IN('products','investment_options') THEN 'mixed' ELSE p.reset_mode END,
 CASE WHEN p.table_name~'^(x_|post|comment|likes|followers|repost|stories|trends|messages|notifications)' THEN 'Comunicação' WHEN p.table_name~'(election|candidac|electoral|voting)' THEN 'Eleições' WHEN p.table_name~'^(parliament|bill|law|decree|dou|constitution|legal_)' THEN 'Parlamento e normas' WHEN p.table_name~'^(agies)' THEN 'AGIES' WHEN p.table_name~'(institutional_terms|justice|criminal|case_|police|prison|sentence|judicial|warrant|fine|appeal|investigation|hearing|penal)' THEN 'Justiça e segurança' WHEN p.table_name~'(part(y|ies)|coalition|alliance)' THEN 'Partidos' WHEN p.table_name~'(business|company|employee|job_|professional|procurement)' THEN 'Empresas e trabalho' WHEN p.table_name~'(account|card|invoice|loan|bank|transaction|payment|bill_of|investment|stock|dividend|currency|exchange)' THEN 'Banco e mercados' WHEN p.table_name~'(residence|housing|lease|room)' THEN 'Moradia' WHEN p.table_name~'(product|cart|market|order|sale|subscription|commerce)' THEN 'Comércio' WHEN p.table_name~'(government|minister|executive|presiden|official)' THEN 'Governo' WHEN p.table_name~'(country|economic|population|price_|infrastructure|region)' THEN 'Economia e infraestrutura' WHEN p.table_name~'(citizen|user_|achievement|inventory|check_in|social)' OR p.table_name='profiles' THEN 'Cidadãos' WHEN p.table_name~'(donation|support|audit|security)' THEN 'Registros protegidos' ELSE 'Serviços e configurações' END,true FROM private.rp_reset_policy()p
 UNION ALL SELECT 'private',t.name,t.classification,t.strategy,'Controle e dados privados',t.backup FROM (VALUES
 ('account_identities','C','keep',true),('admin_development_modes','C','keep',true),('platform_admins','C','keep',true),('deleted_user_snapshots','D','keep',false),('rp_reset_requests','B','keep',false),('rp_launch_backups','B','keep',false),('rp_reset_runtime','B','keep',false),('rp_reset_steps','B','keep',false),('rp_reset_backup_chunks','B','keep',false),('rp_reset_assets','B','keep',false),('rp_reset_targets','B','keep',false),('rp_reset_job_events','B','keep',false),('rp_reset_job_schedules','B','keep',false),
 ('police_occurrence_reporters','A','clear',true),('justice_evidence_uploads','A','clear',true),('agies_task_answers','A','clear',true),('business_daily_effort','A','clear',true),('citizen_need_actions','A','clear',true),('company_operations','A','clear',true),('infrastructure_maintenance','A','clear',true),('population_demand_runs','A','clear',true),('professional_work_answers','A','clear',true),('recurring_billing_cycles','A','clear',true))t(name,classification,strategy,backup)
 UNION ALL SELECT n.nspname,c.relname,CASE WHEN n.nspname='auth' THEN 'C' ELSE 'B' END,'managed',CASE n.nspname WHEN 'auth' THEN 'Autenticação' WHEN 'storage' THEN 'Arquivos' ELSE 'Agendamentos' END,n.nspname='auth' AND c.relname IN('users','identities') FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname IN('auth','storage','cron') AND c.relkind IN('r','p');
$function$;

DO $patch$ DECLARE source text;signature regprocedure; BEGIN
 FOREACH signature IN ARRAY ARRAY['public.admin_process_reset_batch(uuid,text,uuid)'::regprocedure,'private.reset_audit()'::regprocedure] LOOP
  SELECT pg_get_functiondef(signature) INTO source;
  IF source NOT LIKE '%''justice-evidence''%' THEN
   IF source NOT LIKE '%''x-message-attachments''%' THEN RAISE EXCEPTION 'Catálogo de arquivos do reset incompatível: %',signature; END IF;
   source:=replace(source,'''x-message-attachments''','''x-message-attachments'',''justice-evidence''');
   EXECUTE source;
  END IF;
 END LOOP;
END $patch$;
DO $barriers$ DECLARE target regclass;BEGIN
 FOREACH target IN ARRAY ARRAY['public.institutional_terms'::regclass,'public.judicial_electoral_assignments'::regclass,'private.police_occurrence_reporters'::regclass,'private.justice_evidence_uploads'::regclass] LOOP
  IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgrelid=target AND tgname='world_generation_barrier') THEN
   EXECUTE format('CREATE TRIGGER world_generation_barrier BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON %s FOR EACH STATEMENT EXECUTE FUNCTION private.guard_world_mutation()',target);
  END IF;
 END LOOP;
END $barriers$;
REVOKE ALL ON FUNCTION private.rp_reset_policy(),private.reset_catalog() FROM PUBLIC,anon,authenticated,service_role;

