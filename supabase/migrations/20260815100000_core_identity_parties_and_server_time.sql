create or replace function public.get_server_now()
returns timestamptz
language sql
stable
security definer
set search_path = ''
as $$ select clock_timestamp(); $$;

grant execute on function public.get_server_now() to anon, authenticated, service_role;

create or replace function public.set_official_publication_time()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.is_published and (tg_op = 'INSERT' or not coalesce(old.is_published, false)) then
    new.published_at := clock_timestamp();
  elsif not new.is_published then
    new.published_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists decrees_official_publication_time on public.decrees;
create trigger decrees_official_publication_time
before insert or update of is_published on public.decrees
for each row execute function public.set_official_publication_time();

create or replace function public.complete_residency_onboarding(
  p_country_code text,
  p_country_name text,
  p_state_code text,
  p_state_name text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_state text := upper(trim(p_state_code));
  official_state_name text;
begin
  if auth.uid() is null then raise exception 'Usuário não autenticado'; end if;
  if upper(trim(p_country_code)) <> 'BR' then
    raise exception 'O Brasil é o único país disponível nesta etapa do GOV.RP.';
  end if;

  official_state_name := case normalized_state
    when 'AC' then 'Acre' when 'AL' then 'Alagoas' when 'AP' then 'Amapá'
    when 'AM' then 'Amazonas' when 'BA' then 'Bahia' when 'CE' then 'Ceará'
    when 'DF' then 'Distrito Federal' when 'ES' then 'Espírito Santo' when 'GO' then 'Goiás'
    when 'MA' then 'Maranhão' when 'MT' then 'Mato Grosso' when 'MS' then 'Mato Grosso do Sul'
    when 'MG' then 'Minas Gerais' when 'PA' then 'Pará' when 'PB' then 'Paraíba'
    when 'PR' then 'Paraná' when 'PE' then 'Pernambuco' when 'PI' then 'Piauí'
    when 'RJ' then 'Rio de Janeiro' when 'RN' then 'Rio Grande do Norte' when 'RS' then 'Rio Grande do Sul'
    when 'RO' then 'Rondônia' when 'RR' then 'Roraima' when 'SC' then 'Santa Catarina'
    when 'SP' then 'São Paulo' when 'SE' then 'Sergipe' when 'TO' then 'Tocantins'
    else null
  end;
  if official_state_name is null then raise exception 'Estado brasileiro inválido.'; end if;

  update public.profiles
  set country_code = 'BR', country_name = 'Brasil', state_code = normalized_state,
      state_name = official_state_name, onboarding_completed = false, updated_at = clock_timestamp()
  where id = auth.uid();
  if not found then raise exception 'Perfil não encontrado'; end if;
end;
$$;

create or replace function public.admin_reset_citizen_onboarding(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if public.get_user_role(auth.uid()) <> 'Admin' then raise exception 'Apenas administradores podem reiniciar o primeiro acesso.'; end if;
  update public.profiles
  set country_code = null, country_name = null, state_code = null, state_name = null,
      onboarding_completed = false, titulo_eleitor = null, carteira_trabalho = null,
      updated_at = clock_timestamp()
  where id = p_user_id;
  update public.documents set is_valid = false
  where user_id = p_user_id and type in ('CTD', 'Título de Eleitor') and is_valid;
end;
$$;

grant execute on function public.admin_reset_citizen_onboarding(uuid) to authenticated, service_role;

create table if not exists public.party_history (
  id bigint generated by default as identity primary key,
  party_id uuid not null references public.political_parties(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  event_type text not null,
  summary text not null,
  previous_state jsonb not null default '{}'::jsonb,
  current_state jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

update public.political_parties set owner_id = founder_id where owner_id is null;
update public.party_members pm
set role = case
  when pm.user_id = pp.owner_id then 'Dono'::public.party_role
  when pm.user_id = pp.president_id then 'Presidente'::public.party_role
  when pm.user_id = pp.vice_president_id then 'Vice-Presidente'::public.party_role
  else 'Membro'::public.party_role end
from public.political_parties pp where pp.id = pm.party_id;

create or replace function public.protect_party_founder()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.founder_id is distinct from old.founder_id then
    raise exception 'O fundador é um registro histórico permanente e não pode ser transferido.';
  end if;
  return new;
end;
$$;

drop trigger if exists political_parties_immutable_founder on public.political_parties;
create trigger political_parties_immutable_founder
before update of founder_id on public.political_parties
for each row execute function public.protect_party_founder();

create or replace function public.transfer_party_ownership(p_party_id uuid, p_new_founder_id uuid)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid(); old_owner uuid; party_name text;
begin
  select owner_id, name into old_owner, party_name from public.political_parties where id = p_party_id for update;
  if old_owner is null then return json_build_object('success', false, 'message', 'Partido não encontrado.'); end if;
  if actor <> old_owner and public.get_user_role(actor) <> 'Admin' then
    return json_build_object('success', false, 'message', 'Apenas o dono pode transferir a propriedade do partido.');
  end if;
  if p_new_founder_id = old_owner then return json_build_object('success', true, 'message', 'O membro indicado já é o dono.'); end if;
  if not exists (select 1 from public.party_members where party_id=p_party_id and user_id=p_new_founder_id) then
    return json_build_object('success', false, 'message', 'O novo dono precisa ser membro do partido.');
  end if;

  update public.political_parties set owner_id=p_new_founder_id where id=p_party_id;
  update public.party_members set role='Membro' where party_id=p_party_id and user_id=old_owner;
  update public.party_members set role='Dono' where party_id=p_party_id and user_id=p_new_founder_id;
  insert into public.party_history(party_id,actor_id,event_type,summary,previous_state,current_state)
  values(p_party_id,actor,'ownership_transferred','Propriedade partidária transferida.',jsonb_build_object('ownerId',old_owner),jsonb_build_object('ownerId',p_new_founder_id));
  return json_build_object('success', true, 'message', 'Propriedade do partido transferida. O fundador histórico foi preservado.');
end;
$$;

create or replace function public.expel_party_member(p_party_id uuid, p_member_id_to_expel uuid, p_reason text)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid(); actor_role public.party_role; target_role public.party_role;
  actor_rank int; target_rank int; party_name text; member_name text;
begin
  if actor = p_member_id_to_expel then return json_build_object('success',false,'message','Use a opção de desfiliação para sair do partido.'); end if;
  select name into party_name from public.political_parties where id=p_party_id for update;
  select role into actor_role from public.party_members where party_id=p_party_id and user_id=actor;
  select role into target_role from public.party_members where party_id=p_party_id and user_id=p_member_id_to_expel;
  if target_role is null then return json_build_object('success',false,'message','Membro não encontrado no partido.'); end if;
  actor_rank := case actor_role when 'Dono' then 4 when 'Presidente' then 3 when 'Vice-Presidente' then 2 else 1 end;
  target_rank := case target_role when 'Dono' then 4 when 'Presidente' then 3 when 'Vice-Presidente' then 2 else 1 end;
  if public.get_user_role(actor) <> 'Admin' and (actor_role is null or actor_rank <= target_rank or actor_rank < 3) then
    return json_build_object('success',false,'message','A hierarquia não permite expulsar este integrante.');
  end if;
  if nullif(trim(p_reason),'') is null then return json_build_object('success',false,'message','Informe o motivo da expulsão.'); end if;

  select full_name into member_name from public.profiles where id=p_member_id_to_expel;
  update public.political_parties set president_id=null where id=p_party_id and president_id=p_member_id_to_expel;
  update public.political_parties set vice_president_id=null where id=p_party_id and vice_president_id=p_member_id_to_expel;
  delete from public.party_members where party_id=p_party_id and user_id=p_member_id_to_expel;
  insert into public.party_history(party_id,actor_id,event_type,summary,previous_state)
  values(p_party_id,actor,'member_expelled',coalesce(member_name,'Membro')||' foi expulso: '||trim(p_reason),jsonb_build_object('userId',p_member_id_to_expel,'role',target_role));
  insert into public.notifications(user_id,sender_id,type,content,link)
  values(p_member_id_to_expel,actor,'party_expelled','Você foi expulso do partido '||party_name||'. Motivo: '||trim(p_reason),'/services/political-parties');
  return json_build_object('success',true,'message','Membro expulso com sucesso.');
end;
$$;

create or replace function public.disaffiliate_from_party(p_party_id uuid, p_new_founder_id uuid default null)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid(); party public.political_parties%rowtype; member_count int;
begin
  select * into party from public.political_parties where id=p_party_id for update;
  if not found or not exists(select 1 from public.party_members where party_id=p_party_id and user_id=actor) then
    return json_build_object('success',false,'message','Você não é membro deste partido.');
  end if;
  select count(*) into member_count from public.party_members where party_id=p_party_id;
  if member_count=1 then
    delete from public.political_parties where id=p_party_id;
    return json_build_object('success',true,'message','O partido foi encerrado porque não restaram membros.');
  end if;
  if party.owner_id=actor then
    if p_new_founder_id is null or p_new_founder_id=actor or not exists(select 1 from public.party_members where party_id=p_party_id and user_id=p_new_founder_id) then
      return json_build_object('success',false,'message','Transfira a propriedade para outro membro antes de sair.');
    end if;
    update public.political_parties set owner_id=p_new_founder_id,
      president_id=case when president_id=actor then null else president_id end,
      vice_president_id=case when vice_president_id=actor then null else vice_president_id end
    where id=p_party_id;
    update public.party_members set role='Dono' where party_id=p_party_id and user_id=p_new_founder_id;
  else
    update public.political_parties set president_id=null where id=p_party_id and president_id=actor;
    update public.political_parties set vice_president_id=null where id=p_party_id and vice_president_id=actor;
  end if;
  delete from public.party_members where party_id=p_party_id and user_id=actor;
  insert into public.party_history(party_id,actor_id,event_type,summary,current_state)
  values(p_party_id,actor,'member_left','Integrante desfiliado do partido.',jsonb_build_object('newOwnerId',case when party.owner_id=actor then p_new_founder_id else party.owner_id end));
  return json_build_object('success',true,'message','Desfiliação concluída. O registro do fundador foi preservado.');
end;
$$;

create or replace function public.update_party_details(
  p_party_id uuid, p_name text, p_acronym text, p_ideology text, p_statute text,
  p_logo_url text, p_owner_id uuid, p_president_id uuid, p_vice_president_id uuid,
  p_description text, p_orientation public.political_orientation
)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid(); party public.political_parties%rowtype; is_admin boolean;
  prior jsonb;
begin
  select * into party from public.political_parties where id=p_party_id for update;
  if not found then return json_build_object('success',false,'message','Partido não encontrado.'); end if;
  is_admin := public.get_user_role(actor)='Admin';
  if not is_admin and actor not in (party.owner_id,party.president_id) then
    return json_build_object('success',false,'message','Você não tem permissão para editar este partido.');
  end if;
  if not is_admin and actor=party.president_id and p_owner_id is distinct from party.owner_id then
    return json_build_object('success',false,'message','O presidente não pode transferir a propriedade do partido.');
  end if;
  if p_owner_id is null or not exists(select 1 from public.party_members where party_id=p_party_id and user_id=p_owner_id) then
    return json_build_object('success',false,'message','O dono precisa ser integrante do partido.');
  end if;
  if p_president_id is not null and not exists(select 1 from public.party_members where party_id=p_party_id and user_id=p_president_id) then
    return json_build_object('success',false,'message','O presidente precisa ser integrante do partido.');
  end if;
  if p_vice_president_id is not null and not exists(select 1 from public.party_members where party_id=p_party_id and user_id=p_vice_president_id) then
    return json_build_object('success',false,'message','O vice-presidente precisa ser integrante do partido.');
  end if;
  if p_president_id is not null and p_president_id=p_owner_id then p_president_id := null; end if;
  if p_vice_president_id is not null and p_vice_president_id in (p_owner_id,p_president_id) then
    return json_build_object('success',false,'message','Uma pessoa não pode ocupar dois cargos simultaneamente.');
  end if;

  prior := jsonb_build_object('name',party.name,'acronym',party.acronym,'ownerId',party.owner_id,'presidentId',party.president_id,'vicePresidentId',party.vice_president_id);
  update public.political_parties set name=trim(p_name),acronym=upper(trim(p_acronym)),ideology=trim(p_ideology),
    statute=p_statute,logo_url=p_logo_url,owner_id=p_owner_id,president_id=p_president_id,
    vice_president_id=p_vice_president_id,description=p_description,orientation=p_orientation
  where id=p_party_id;
  update public.party_members set role=case
    when user_id=p_owner_id then 'Dono'::public.party_role
    when user_id=p_president_id then 'Presidente'::public.party_role
    when user_id=p_vice_president_id then 'Vice-Presidente'::public.party_role
    else 'Membro'::public.party_role end where party_id=p_party_id;
  insert into public.party_history(party_id,actor_id,event_type,summary,previous_state,current_state)
  values(p_party_id,actor,'party_updated','Estrutura e dados partidários atualizados.',prior,
    jsonb_build_object('name',trim(p_name),'acronym',upper(trim(p_acronym)),'ownerId',p_owner_id,'presidentId',p_president_id,'vicePresidentId',p_vice_president_id));
  return json_build_object('success',true,'message','Partido atualizado com sucesso.');
end;
$$;

