-- Portfólio por quantidade, preço médio, histórico e operações atômicas.

alter table public.investment_options
  add column if not exists asset_symbol text,
  add column if not exists asset_type text not null default 'fixed_income',
  add column if not exists current_unit_price numeric(20,6) not null default 1,
  add column if not exists price_updated_at timestamptz not null default now();

update public.investment_options
set asset_symbol=coalesce(nullif(asset_symbol,''),upper(substr(regexp_replace(name,'[^A-Za-z0-9]','','g'),1,8))),
    current_unit_price=greatest(current_unit_price,0.000001);

alter table public.user_investments
  add column if not exists quantity numeric(24,8) not null default 0,
  add column if not exists average_unit_price numeric(20,6) not null default 1,
  add column if not exists realized_result numeric(20,2) not null default 0;

update public.user_investments ui
set average_unit_price=greatest(coalesce(io.current_unit_price,1),0.000001),
    quantity=round(ui.amount_invested/greatest(coalesce(io.current_unit_price,1),0.000001),8)
from public.investment_options io
where io.id=ui.investment_id and ui.quantity=0;

with grouped as (
  select user_id,investment_id,(array_agg(id order by created_at,id))[1] keep_id,sum(amount_invested) total_amount,sum(quantity) total_quantity
  from public.user_investments group by user_id,investment_id having count(*)>1
), updated as (
  update public.user_investments ui set amount_invested=g.total_amount,quantity=g.total_quantity
  from grouped g where ui.id=g.keep_id returning ui.id
)
delete from public.user_investments ui using grouped g
where ui.user_id=g.user_id and ui.investment_id=g.investment_id and ui.id<>g.keep_id;

create unique index if not exists user_investments_user_asset_unique
on public.user_investments(user_id,investment_id);

create table if not exists public.investment_operations (
  id uuid primary key default gen_random_uuid(),
  idempotency_key uuid not null unique,
  user_id uuid not null references public.profiles(id) on delete cascade,
  investment_id uuid not null references public.investment_options(id) on delete restrict,
  holding_id uuid references public.user_investments(id) on delete set null,
  operation_type text not null check(operation_type in('buy','sell')),
  quantity numeric(24,8) not null check(quantity>0),
  unit_price numeric(20,6) not null check(unit_price>0),
  gross_amount numeric(20,2) not null check(gross_amount>=0),
  realized_result numeric(20,2) not null default 0,
  transaction_id uuid references public.transactions(id) on delete set null,
  executed_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.investment_portfolio_snapshots (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  total_cost numeric(20,2) not null,
  market_value numeric(20,2) not null,
  unrealized_result numeric(20,2) not null,
  captured_at timestamptz not null default now()
);

create or replace function public.trade_investment(p_investment_id uuid,p_operation_type text,p_quantity numeric,p_idempotency_key uuid)
returns jsonb
language plpgsql security definer set search_path='' as $$
declare
  actor uuid:=auth.uid(); option public.investment_options%rowtype; account public.accounts%rowtype;
  holding public.user_investments%rowtype; operation public.investment_operations%rowtype;
  amount numeric(20,2); new_quantity numeric(24,8); new_average numeric(20,6); realized numeric(20,2):=0; transaction_id uuid;
  portfolio_cost numeric(20,2); portfolio_value numeric(20,2);
begin
  if actor is null then raise exception 'Usuário não autenticado.'; end if;
  if p_operation_type not in('buy','sell') or p_quantity is null or p_quantity<=0 then raise exception 'Operação ou quantidade inválida.'; end if;
  if p_idempotency_key is null then raise exception 'Identificador idempotente obrigatório.'; end if;
  select * into operation from public.investment_operations where idempotency_key=p_idempotency_key;
  if found then return jsonb_build_object('success',true,'message','Operação já processada.','operation',to_jsonb(operation)); end if;
  select * into option from public.investment_options where id=p_investment_id and is_active for update;
  if not found then raise exception 'Investimento indisponível.'; end if;
  amount:=round(p_quantity*option.current_unit_price,2);
  if amount<=0 then raise exception 'Valor da operação inválido.'; end if;
  select * into account from public.accounts where user_id=actor for update;
  if not found then raise exception 'Conta bancária não encontrada.'; end if;
  select * into holding from public.user_investments where user_id=actor and investment_id=p_investment_id for update;

  if p_operation_type='buy' then
    if amount<option.minimum_amount then raise exception 'Valor abaixo da aplicação mínima.'; end if;
    if account.balance<amount then raise exception 'Saldo insuficiente.'; end if;
    update public.accounts set balance=balance-amount,updated_at=clock_timestamp() where id=account.id;
    if holding.id is null then
      insert into public.user_investments(user_id,investment_id,amount_invested,quantity,average_unit_price,start_date,updated_at)
      values(actor,p_investment_id,amount,p_quantity,option.current_unit_price,clock_timestamp(),clock_timestamp()) returning * into holding;
    else
      new_quantity:=holding.quantity+p_quantity;
      new_average:=round(((holding.quantity*holding.average_unit_price)+amount)/new_quantity,6);
      update public.user_investments set quantity=new_quantity,average_unit_price=new_average,
        amount_invested=round(new_quantity*new_average,2),is_active=true,updated_at=clock_timestamp()
      where id=holding.id returning * into holding;
    end if;
    insert into public.transactions(from_account_id,amount,type,description,metadata)
    values(account.id,amount,'investment_buy','Compra de '||option.asset_symbol,jsonb_build_object('investmentId',option.id,'quantity',p_quantity,'unitPrice',option.current_unit_price,'idempotencyKey',p_idempotency_key)) returning id into transaction_id;
  else
    if holding.id is null or holding.quantity<p_quantity then raise exception 'Quantidade insuficiente para venda.'; end if;
    realized:=round(amount-(p_quantity*holding.average_unit_price),2);
    update public.accounts set balance=balance+amount,updated_at=clock_timestamp() where id=account.id;
    new_quantity:=holding.quantity-p_quantity;
    if new_quantity<=0.00000001 then
      update public.user_investments set quantity=0,amount_invested=0,is_active=false,realized_result=realized_result+realized,updated_at=clock_timestamp() where id=holding.id returning * into holding;
    else
      update public.user_investments set quantity=new_quantity,amount_invested=round(new_quantity*average_unit_price,2),realized_result=realized_result+realized,updated_at=clock_timestamp() where id=holding.id returning * into holding;
    end if;
    insert into public.transactions(to_account_id,amount,type,description,metadata)
    values(account.id,amount,'investment_sell','Venda de '||option.asset_symbol,jsonb_build_object('investmentId',option.id,'quantity',p_quantity,'unitPrice',option.current_unit_price,'realizedResult',realized,'idempotencyKey',p_idempotency_key)) returning id into transaction_id;
  end if;

  insert into public.investment_operations(idempotency_key,user_id,investment_id,holding_id,operation_type,quantity,unit_price,gross_amount,realized_result,transaction_id)
  values(p_idempotency_key,actor,p_investment_id,holding.id,p_operation_type,p_quantity,option.current_unit_price,amount,realized,transaction_id) returning * into operation;
  select coalesce(sum(ui.quantity*ui.average_unit_price),0),coalesce(sum(ui.quantity*io.current_unit_price),0)
  into portfolio_cost,portfolio_value from public.user_investments ui join public.investment_options io on io.id=ui.investment_id where ui.user_id=actor and ui.is_active;
  insert into public.investment_portfolio_snapshots(user_id,total_cost,market_value,unrealized_result)
  values(actor,round(portfolio_cost,2),round(portfolio_value,2),round(portfolio_value-portfolio_cost,2));
  return jsonb_build_object('success',true,'message',case when p_operation_type='buy' then 'Compra realizada com sucesso.' else 'Venda realizada com sucesso.' end,'operation',to_jsonb(operation),'holding',to_jsonb(holding));
exception when unique_violation then
  select * into operation from public.investment_operations where idempotency_key=p_idempotency_key;
  return jsonb_build_object('success',true,'message','Operação já processada.','operation',to_jsonb(operation));
end; $$;

create or replace function public.invest(p_investment_id uuid,p_amount numeric)
returns jsonb language plpgsql security definer set search_path='' as $$
declare price numeric;
begin
  select current_unit_price into price from public.investment_options where id=p_investment_id;
  if price is null or p_amount is null or p_amount<=0 then return jsonb_build_object('success',false,'message','Valor ou investimento inválido.'); end if;
  return public.trade_investment(p_investment_id,'buy',p_amount/price,gen_random_uuid());
exception when others then return jsonb_build_object('success',false,'message',sqlerrm); end; $$;

create or replace function public.withdraw(p_user_investment_id uuid,p_amount numeric)
returns jsonb language plpgsql security definer set search_path='' as $$
declare investment uuid; price numeric;
begin
  select ui.investment_id,io.current_unit_price into investment,price from public.user_investments ui join public.investment_options io on io.id=ui.investment_id where ui.id=p_user_investment_id and ui.user_id=auth.uid();
  if investment is null or p_amount is null or p_amount<=0 then return jsonb_build_object('success',false,'message','Valor ou investimento inválido.'); end if;
  return public.trade_investment(investment,'sell',p_amount/price,gen_random_uuid());
exception when others then return jsonb_build_object('success',false,'message',sqlerrm); end; $$;

