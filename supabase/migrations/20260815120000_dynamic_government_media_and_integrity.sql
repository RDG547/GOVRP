create or replace function public.apply_government_impact(
  p_domain text,p_event_type text,p_summary text,p_player_delta numeric default 0,p_simulation_delta numeric default 0,
  p_source_table text default null,p_source_id text default null,p_metadata jsonb default '{}'::jsonb
)
returns public.government_popularity_state
language plpgsql security definer set search_path='' as $$
declare state public.government_popularity_state%rowtype; delta numeric; before_score numeric;
begin
  select * into state from public.government_popularity_state where country_code='BR' for update;
  delta:=round(coalesce(p_player_delta,0)*state.player_activity_weight+coalesce(p_simulation_delta,0)*state.simulation_weight,4);
  before_score:=state.score;
  update public.government_popularity_state set score=least(100,greatest(0,score+delta)),trend=delta,
    factor_snapshot=coalesce(p_metadata,'{}'::jsonb),revision=revision+1,updated_at=clock_timestamp()
  where country_code='BR' returning * into state;
  insert into public.government_popularity_events(country_code,domain,event_type,summary,player_delta,simulation_delta,applied_delta,score_before,score_after,source_table,source_id,actor_id,metadata)
  values('BR',p_domain,p_event_type,p_summary,coalesce(p_player_delta,0),coalesce(p_simulation_delta,0),delta,before_score,state.score,p_source_table,p_source_id,auth.uid(),coalesce(p_metadata,'{}'::jsonb));
  return state;
end; $$;

create or replace function public.sync_economic_indicator_to_national_history()
returns trigger language plpgsql security definer set search_path='' as $$
declare indicator_value numeric; simulation_delta numeric:=0;
begin
  indicator_value:=coalesce(new.real_value,new.nominal_value);
  if indicator_value is null then return new; end if;
  insert into public.national_indicator_points(country_code,indicator_code,value,unit,domain,source_type,source_table,source_id,metadata)
  values('BR',new.indicator_code,indicator_value,new.unit,'economy','rp_simulation','economic_indicators',new.id::text,new.metadata);
  simulation_delta:=case
    when new.indicator_code like 'gdp_growth%' then greatest(-3,least(3,coalesce(new.variation,indicator_value)/4))
    when new.indicator_code like 'unemployment%' then greatest(-3,least(3,-coalesce(new.variation,0)/3))
    when new.indicator_code like 'inflation%' then greatest(-3,least(3,-abs(coalesce(new.variation,0))/4))
    else 0 end;
  if simulation_delta<>0 then perform public.apply_government_impact('economy','indicator_updated','Indicador nacional recalculado.',0,simulation_delta,'economic_indicators',new.id::text,jsonb_build_object('indicator',new.indicator_code,'value',indicator_value)); end if;
  return new;
end; $$;
drop trigger if exists economic_indicators_national_history on public.economic_indicators;
create trigger economic_indicators_national_history after insert on public.economic_indicators for each row execute function public.sync_economic_indicator_to_national_history();

insert into public.national_indicator_points(country_code,indicator_code,value,unit,domain,source_type,source_table,source_id,recorded_at,metadata)
select 'BR',ei.indicator_code,coalesce(ei.real_value,ei.nominal_value),ei.unit,'economy',
  case when coalesce(ei.metadata->>'origin','')='real_baseline' then 'real_baseline' else 'rp_simulation' end,
  'economic_indicators',ei.id::text,ei.created_at,ei.metadata
from public.economic_indicators ei where coalesce(ei.real_value,ei.nominal_value) is not null
and not exists(select 1 from public.national_indicator_points p where p.source_table='economic_indicators' and p.source_id=ei.id::text);

