create or replace function public.manage_government_ministry(p_ministry_id uuid,p_name text,p_acronym text,p_description text,p_responsibilities text[],p_annual_budget numeric,p_is_active boolean)
returns public.government_ministries language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); result public.government_ministries%rowtype;
begin
  if public.get_user_role(actor) not in('Presidente','Admin') then raise exception 'Apenas a Presidência pode gerir ministérios.'; end if;
  if length(trim(coalesce(p_name,'')))<4 or p_annual_budget<0 then raise exception 'Dados ministeriais inválidos.'; end if;
  if p_ministry_id is null then
    insert into public.government_ministries(name,acronym,description,responsibilities,annual_budget,is_active,created_by)
    values(trim(p_name),upper(nullif(trim(p_acronym),'')),trim(p_description),coalesce(p_responsibilities,'{}'),p_annual_budget,coalesce(p_is_active,true),actor) returning * into result;
  else
    update public.government_ministries set name=trim(p_name),acronym=upper(nullif(trim(p_acronym),'')),description=trim(p_description),
      responsibilities=coalesce(p_responsibilities,'{}'),annual_budget=p_annual_budget,is_active=coalesce(p_is_active,true),updated_at=clock_timestamp()
    where id=p_ministry_id returning * into result;
  end if;
  return result;
end; $$;

create or replace function public.record_minister_impact(p_minister_id uuid,p_summary text,p_reputation_delta numeric,p_performance_delta numeric,p_metadata jsonb default '{}'::jsonb)
returns public.ministers language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); result public.ministers%rowtype;
begin
  if public.get_user_role(actor) not in('Presidente','Admin') and not exists(select 1 from public.ministers where user_id=actor and id=p_minister_id and status='active') then raise exception 'Sem permissão para registrar impacto ministerial.'; end if;
  if length(trim(coalesce(p_summary,'')))<10 then raise exception 'Descreva o impacto.'; end if;
  update public.ministers set reputation_score=least(100,greatest(0,reputation_score+p_reputation_delta)),performance_score=least(100,greatest(0,performance_score+p_performance_delta)) where id=p_minister_id and status='active' returning * into result;
  if result.id is null then raise exception 'Ministro ativo não encontrado.'; end if;
  insert into public.minister_history(minister_profile_id,ministry_id,event_type,summary,reputation_delta,performance_delta,actor_id,metadata)
  values(result.user_id,result.ministry_id,'impact',trim(p_summary),p_reputation_delta,p_performance_delta,actor,coalesce(p_metadata,'{}'));
  perform public.apply_government_impact('politics','minister_impact',trim(p_summary),p_reputation_delta/5,p_performance_delta/10,'ministers',result.id::text,p_metadata);
  return result;
end; $$;

create or replace function public.appoint_minister(p_user_id uuid,p_ministry text)
returns json language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); ministry public.government_ministries%rowtype; current_holder uuid; result public.ministers%rowtype;
begin
  if public.get_user_role(actor) not in('Presidente','Admin') then return json_build_object('success',false,'message','Apenas a Presidência pode nomear ministros.'); end if;
  select * into ministry from public.government_ministries where name=p_ministry and is_active for update;
  if not found then return json_build_object('success',false,'message','Ministério inexistente ou inativo.'); end if;
  select user_id into current_holder from public.ministers where ministry_id=ministry.id and status='active' for update;
  if current_holder is not null and current_holder<>p_user_id then
    update public.ministers set status='dismissed',ended_at=clock_timestamp() where user_id=current_holder;
    insert into public.minister_history(minister_profile_id,ministry_id,event_type,summary,actor_id) values(current_holder,ministry.id,'dismissed','Exoneração por substituição ministerial.',actor);
  end if;
  insert into public.ministers(user_id,ministry,ministry_id,appointed_by,status,appointed_at,ended_at)
  values(p_user_id,ministry.name,ministry.id,actor,'active',clock_timestamp(),null)
  on conflict(user_id) do update set ministry=excluded.ministry,ministry_id=excluded.ministry_id,appointed_by=actor,status='active',appointed_at=clock_timestamp(),ended_at=null
  returning * into result;
  update public.profiles set role='Ministro' where id=p_user_id;
  insert into public.minister_history(minister_profile_id,ministry_id,event_type,summary,actor_id) values(p_user_id,ministry.id,'appointed','Nomeação para '||ministry.name||'.',actor);
  perform public.apply_government_impact('politics','minister_appointed','Nomeação ministerial realizada.',.2,0,'ministers',result.id::text,jsonb_build_object('ministerId',p_user_id,'ministry',ministry.name));
  return json_build_object('success',true,'message','Ministro nomeado com sucesso.','minister',to_jsonb(result));
end; $$;

create or replace function public.dismiss_minister(p_user_id uuid)
returns json language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); result public.ministers%rowtype;
begin
  if public.get_user_role(actor) not in('Presidente','Admin') then return json_build_object('success',false,'message','Apenas a Presidência pode exonerar ministros.'); end if;
  update public.ministers set status='dismissed',ended_at=clock_timestamp() where user_id=p_user_id and status='active' returning * into result;
  if result.id is null then return json_build_object('success',false,'message','Ministro ativo não encontrado.'); end if;
  update public.profiles set role='Cidadão' where id=p_user_id and role='Ministro';
  insert into public.minister_history(minister_profile_id,ministry_id,event_type,summary,actor_id) values(p_user_id,result.ministry_id,'dismissed','Exoneração de '||result.ministry||'.',actor);
  perform public.apply_government_impact('politics','minister_dismissed','Exoneração ministerial.',-.3,0,'ministers',result.id::text,jsonb_build_object('ministerId',p_user_id,'ministry',result.ministry));
  return json_build_object('success',true,'message','Ministro exonerado com sucesso.');
end; $$;

