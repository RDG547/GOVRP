create or replace function public.publish_media_coverage(p_event_type text,p_event_id text,p_title text,p_facts text)
returns integer language plpgsql security definer set search_path='' as $$
declare outlet public.media_outlets%rowtype; framing_text text; published_count int:=0;
begin
  if public.get_user_role(auth.uid()) not in('Admin','Presidente') then raise exception 'Sem permissão para distribuir pauta institucional.'; end if;
  if length(trim(coalesce(p_facts,'')))<20 then raise exception 'Informe os fatos verificáveis da pauta.'; end if;
  for outlet in select * from public.media_outlets where is_active loop
    framing_text:=case outlet.editorial_profile
      when 'governista' then 'O governo destaca os resultados e a continuidade da medida.'
      when 'oposicao' then 'A oposição questiona custos, riscos e promessas ainda não comprovadas.'
      when 'sensacionalista' then 'A repercussão cresce em meio a disputas e forte reação pública.'
      else 'O veículo apresenta fatos, contexto e contrapontos disponíveis.' end;
    insert into public.news_articles(author_id,title,content,outlet_id,framing,source_event_type,source_event_id)
    values(outlet.editor_id,p_title,trim(p_facts)||E'\n\n'||framing_text,outlet.id,outlet.editorial_profile,p_event_type,p_event_id);
    published_count:=published_count+1;
  end loop;
  return published_count;
end; $$;

create or replace function public.transition_integrity_case(p_case_id uuid,p_new_status text,p_summary text,p_investigation_id uuid default null,p_commission_id uuid default null)
returns public.public_integrity_cases language plpgsql security definer set search_path='' as $$
declare actor uuid:=auth.uid(); current_case public.public_integrity_cases%rowtype; result public.public_integrity_cases%rowtype; allowed boolean:=false;
begin
  if not public.justice_has_role(array['Admin','Policial','Police','Delegado','Promotor','Juiz']) and public.get_user_role(actor) not in('Presidente da Câmara','Presidente do Senado') then raise exception 'Autoridade sem competência para esta etapa.'; end if;
  select * into current_case from public.public_integrity_cases where id=p_case_id for update;
  if not found then raise exception 'Caso de integridade não encontrado.'; end if;
  allowed:=case current_case.status
    when 'suspicion' then p_new_status in('journalistic_investigation','police_investigation','archived')
    when 'journalistic_investigation' then p_new_status in('police_investigation','archived')
    when 'police_investigation' then p_new_status in('public_prosecution','archived')
    when 'public_prosecution' then p_new_status in('judicial_process','archived')
    when 'judicial_process' then p_new_status in('convicted','acquitted') else false end;
  if not allowed then raise exception 'Transição de integridade inválida.'; end if;
  update public.public_integrity_cases set status=p_new_status,investigation_id=coalesce(p_investigation_id,investigation_id),commission_id=coalesce(p_commission_id,commission_id),updated_at=clock_timestamp() where id=p_case_id returning * into result;
  insert into public.public_integrity_case_events(case_id,previous_status,new_status,summary,actor_id) values(p_case_id,current_case.status,p_new_status,trim(p_summary),actor);
  if p_new_status='convicted' then perform public.apply_government_impact('integrity','corruption_conviction','Condenação em caso de integridade pública.',-6,-2,'public_integrity_cases',p_case_id::text,'{}'); end if;
  return result;
end; $$;

