BEGIN;
-- Regular browser roles cannot write mandates directly. Resolve the official
-- role, active term and house in one idempotent server operation.
CREATE OR REPLACE FUNCTION public.ensure_current_parliament_member(p_house_id uuid)
RETURNS public.parliament_members LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE p public.profiles%rowtype; m public.parliament_members%rowtype; h public.parliament_houses%rowtype; assignment public.election_office_assignments%rowtype; starts date; ends date; senate boolean;
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'AUTHENTICATION_REQUIRED'; END IF;
 SELECT * INTO p FROM public.profiles WHERE id=auth.uid() AND deleted_at IS NULL FOR UPDATE;
 IF NOT FOUND OR p.role NOT IN('Deputado','Senador','Presidente da Câmara','Presidente da Câmara dos Deputados','Vice-Presidente da Câmara dos Deputados','Presidente do Senado','Vice-Presidente do Senado','Vice-Presidente do Senado Federal') THEN RAISE EXCEPTION 'PARLIAMENT_AUTHORITY_REQUIRED'; END IF;
 senate:=p.role ILIKE '%senad%';
 SELECT * INTO h FROM public.parliament_houses WHERE id=p_house_id;
 IF NOT FOUND OR (senate AND h.name NOT ILIKE '%senado%') OR (NOT senate AND h.name NOT ILIKE '%câmara%' AND h.name NOT ILIKE '%camara%' AND h.name NOT ILIKE '%deputad%') THEN RAISE EXCEPTION 'PARLIAMENT_HOUSE_MISMATCH'; END IF;
 SELECT * INTO m FROM public.parliament_members WHERE user_id=p.id AND house_id=h.id AND term_start_date<=current_date AND (term_end_date IS NULL OR term_end_date>=current_date) ORDER BY term_start_date DESC LIMIT 1;
 IF FOUND THEN RETURN m; END IF;
 SELECT * INTO assignment FROM public.election_office_assignments WHERE profile_id=p.id AND status='active' AND term_starts_at<=clock_timestamp() AND term_ends_at>clock_timestamp() ORDER BY assigned_at DESC LIMIT 1;
 IF FOUND THEN starts:=assignment.term_starts_at::date; ends:=assignment.term_ends_at::date;
 ELSIF p.manual_role_override AND NOT public.election_supersedes_manual_role(p.role,p.role_assigned_at) THEN
   starts:=coalesce(p.role_assigned_at,p.updated_at,p.created_at)::date; ends:=(starts+interval '1 month')::date;
   IF ends<current_date THEN RAISE EXCEPTION 'PARLIAMENT_AUTHORITY_REQUIRED'; END IF;
 ELSE RAISE EXCEPTION 'PARLIAMENT_AUTHORITY_REQUIRED'; END IF;
 INSERT INTO public.parliament_members(user_id,house_id,term_start_date,term_end_date) VALUES(p.id,h.id,starts,ends) RETURNING * INTO m;
 RETURN m;
END $$;
REVOKE ALL ON FUNCTION public.ensure_current_parliament_member(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ensure_current_parliament_member(uuid) TO authenticated;
ALTER FUNCTION public.ensure_current_parliament_member(uuid) OWNER TO postgres;
ALTER TABLE public.dou_entries ADD COLUMN IF NOT EXISTS publication_number bigint GENERATED BY DEFAULT AS IDENTITY;
GRANT USAGE ON SEQUENCE public.dou_entries_publication_number_seq TO authenticated,service_role;
CREATE UNIQUE INDEX IF NOT EXISTS dou_publication_number_once ON public.dou_entries(publication_number);
NOTIFY pgrst,'reload schema';
COMMIT;
