-- Panorama nacional e Economia Nacional passam a ler o mesmo estado autoritativo.
-- O PIB brasileiro é normalizado para BRL, moeda usada pelo motor e pelos setores.

update public.country_rp_states state
set economic_current = jsonb_set(
      jsonb_set(
        state.economic_current,
        '{gdp}',
        to_jsonb(
          (state.economic_current->>'gdp')::numeric
          * (state.economic_current->>'exchangeUsd')::numeric
        ),
        true
      ),
      '{gdpCurrency}',
      to_jsonb('BRL'::text),
      true
    )
where state.country_code = 'BR'
  and upper(coalesce(state.economic_current->>'gdpCurrency', 'USD')) = 'USD'
  and nullif(state.economic_current->>'gdp', '') is not null
  and nullif(state.economic_current->>'exchangeUsd', '') is not null;

update public.country_rp_states state
set economic_baseline = jsonb_set(
      jsonb_set(
        state.economic_baseline,
        '{gdp}',
        to_jsonb(
          (state.economic_baseline->>'gdp')::numeric
          * (state.economic_baseline->>'exchangeUsd')::numeric
        ),
        true
      ),
      '{gdpCurrency}',
      to_jsonb('BRL'::text),
      true
    )
where state.country_code = 'BR'
  and upper(coalesce(state.economic_baseline->>'gdpCurrency', 'USD')) = 'USD'
  and nullif(state.economic_baseline->>'gdp', '') is not null
  and nullif(state.economic_baseline->>'exchangeUsd', '') is not null;

create table if not exists public.country_rp_economic_snapshots (
  id bigint generated by default as identity primary key,
  country_code text not null references public.country_rp_states(country_code) on delete cascade,
  revision bigint not null,
  economic_state jsonb not null,
  event_type text,
  recorded_at timestamptz not null default now(),
  constraint country_rp_economic_snapshots_state_object
    check (jsonb_typeof(economic_state) = 'object'),
  constraint country_rp_economic_snapshots_country_revision_key
    unique (country_code, revision)
);

create index if not exists country_rp_economic_snapshots_timeline_idx
on public.country_rp_economic_snapshots(country_code, recorded_at desc);

create or replace function public.record_country_rp_economic_snapshot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.economic_current is not distinct from new.economic_current then
    return new;
  end if;

  insert into public.country_rp_economic_snapshots (
    country_code,
    revision,
    economic_state,
    event_type,
    recorded_at
  ) values (
    new.country_code,
    new.revision,
    new.economic_current,
    new.last_event_type,
    new.updated_at
  )
  on conflict (country_code, revision) do update
  set economic_state = excluded.economic_state,
      event_type = excluded.event_type,
      recorded_at = excluded.recorded_at;

  return new;
end;
$$;
drop trigger if exists country_rp_states_record_economy on public.country_rp_states;
create trigger country_rp_states_record_economy
after update of economic_current on public.country_rp_states
for each row execute function public.record_country_rp_economic_snapshot();

insert into public.country_rp_economic_snapshots (
  country_code,
  revision,
  economic_state,
  event_type,
  recorded_at
)
select
  country_code,
  revision,
  economic_current,
  coalesce(last_event_type, 'rp_reference_snapshot'),
  updated_at
from public.country_rp_states
where is_playable
  and reference_snapshot_at is not null
on conflict (country_code, revision) do nothing;

alter table public.country_rp_economic_snapshots enable row level security;

drop policy if exists country_rp_economic_snapshots_public_read
on public.country_rp_economic_snapshots;
create policy country_rp_economic_snapshots_public_read
on public.country_rp_economic_snapshots for select
to anon, authenticated
using (true);

grant select on public.country_rp_economic_snapshots to anon, authenticated;
grant all on public.country_rp_economic_snapshots to service_role;

